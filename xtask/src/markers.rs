//! Work markers: the project's only allowed form of "unfinished" comment.
//!
//! A work marker is the four-letter tag in [`TAG`] followed by
//! `(M<n>): <description>`, where `M<n>` is a milestone that has a `## M<n>`
//! section in ROADMAP.md (a split milestone adds a letter: `M9b`). The open markers are mirrored into a generated
//! table in ROADMAP.md, so unfinished work can never be silent. The banned
//! tag in [`BANNED`] is rejected outright. Markdown files are not scanned, so
//! documentation can discuss the convention freely.
//!
//! (The tags are assembled with `concat!` so this file does not flag itself.)

use std::collections::BTreeSet;
use std::fmt;
use std::path::{Path, PathBuf};

use crate::Result;

/// The work-marker tag.
pub(crate) const TAG: &str = concat!("TO", "DO");
/// Tags that are not allowed at all; use [`TAG`] with a milestone instead.
pub(crate) const BANNED: &str = concat!("FIX", "ME");

pub(crate) const ROADMAP: &str = "ROADMAP.md";
pub(crate) const TABLE_BEGIN: &str =
    "<!-- open-work:begin (generated by `cargo xtask todos --write`) -->";
pub(crate) const TABLE_END: &str = "<!-- open-work:end -->";

/// A milestone: its number and, for a split one, its letter (`M9b`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub(crate) struct Milestone {
    pub(crate) number: u32,
    pub(crate) part: Option<char>,
}

impl Milestone {
    /// Reads `<n>` or `<n><letter>` at the start of `s` (after the `M`);
    /// returns it and how many bytes it took.
    fn parse_prefix(s: &str) -> Option<(Self, usize)> {
        let digits = s.chars().take_while(char::is_ascii_digit).count();
        let number = s[..digits].parse().ok()?;
        let part = s[digits..].chars().next().filter(char::is_ascii_lowercase);
        Some((
            Self { number, part },
            digits + part.map_or(0, char::len_utf8),
        ))
    }
}

impl fmt::Display for Milestone {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "M{}", self.number)?;
        if let Some(p) = self.part {
            write!(f, "{p}")?;
        }
        Ok(())
    }
}

/// A well-formed work marker found in the repository.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Marker {
    pub(crate) milestone: Milestone,
    pub(crate) path: String,
    pub(crate) line: usize,
    pub(crate) text: String,
}

/// A malformed or banned marker.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Violation {
    pub(crate) path: String,
    pub(crate) line: usize,
    pub(crate) message: String,
}

impl fmt::Display for Violation {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}:{}: {}", self.path, self.line, self.message)
    }
}

#[derive(Debug, Default)]
pub(crate) struct Scan {
    pub(crate) markers: Vec<Marker>,
    pub(crate) violations: Vec<Violation>,
}

/// Scans every non-Markdown text file in `files` (relative to `root`).
pub(crate) fn scan_files(root: &Path, files: &[PathBuf]) -> Result<Scan> {
    let mut scan = Scan::default();
    for rel in files.iter().filter(|p| is_scanned(p)) {
        let bytes = std::fs::read(root.join(rel))
            .map_err(|e| format!("cannot read {}: {e}", rel.display()))?;
        // Binary files cannot contain comments we care about.
        let Ok(text) = String::from_utf8(bytes) else {
            continue;
        };
        scan_text(&rel.to_string_lossy(), &text, &mut scan);
    }
    scan.markers
        .sort_by(|a, b| (a.milestone, &a.path, a.line).cmp(&(b.milestone, &b.path, b.line)));
    Ok(scan)
}

fn is_scanned(path: &Path) -> bool {
    let is_markdown = path.extension().is_some_and(|e| e == "md");
    let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
    !is_markdown && !matches!(name, "LICENSE" | "Cargo.lock")
}

fn scan_text(path: &str, text: &str, scan: &mut Scan) {
    for (idx, line) in text.lines().enumerate() {
        let line_no = idx + 1;
        for _ in word_positions(line, BANNED) {
            scan.violations.push(Violation {
                path: path.to_owned(),
                line: line_no,
                message: format!("`{BANNED}` is not allowed; use `{TAG}(M<n>): <description>`"),
            });
        }
        for start in word_positions(line, TAG) {
            match parse_marker(&line[start + TAG.len()..]) {
                Ok((milestone, text)) => scan.markers.push(Marker {
                    milestone,
                    path: path.to_owned(),
                    line: line_no,
                    text,
                }),
                Err(message) => scan.violations.push(Violation {
                    path: path.to_owned(),
                    line: line_no,
                    message,
                }),
            }
        }
    }
}

/// Byte offsets of `word` in `line` where it is not part of a longer identifier.
fn word_positions<'a>(line: &'a str, word: &'a str) -> impl Iterator<Item = usize> + 'a {
    let is_ident = |c: char| c.is_alphanumeric() || c == '_';
    line.match_indices(word).filter_map(move |(start, _)| {
        let before_ok = !line[..start].chars().next_back().is_some_and(is_ident);
        let after_ok = !line[start + word.len()..]
            .chars()
            .next()
            .is_some_and(is_ident);
        (before_ok && after_ok).then_some(start)
    })
}

/// Parses what follows the tag: `(M<n>): <description>`.
fn parse_marker(rest: &str) -> std::result::Result<(Milestone, String), String> {
    let malformed = || format!("malformed work marker; use `{TAG}(M<n>): <description>`");
    let rest = rest.strip_prefix("(M").ok_or_else(malformed)?;
    let (milestone, len) = Milestone::parse_prefix(rest).ok_or_else(malformed)?;
    let rest = rest[len..].strip_prefix("):").ok_or_else(malformed)?;
    let text = rest.trim();
    let text = text.strip_suffix("*/").unwrap_or(text).trim();
    if text.is_empty() {
        return Err(format!("work marker for {milestone} has no description"));
    }
    Ok((milestone, text.to_owned()))
}

/// Problems for markers that reference a milestone ROADMAP.md does not define.
pub(crate) fn check_milestones_exist(markers: &[Marker], roadmap: &str) -> Vec<String> {
    let defined: BTreeSet<Milestone> = roadmap
        .lines()
        .filter_map(|l| l.strip_prefix("## M"))
        .filter_map(|l| Milestone::parse_prefix(l).map(|(m, _)| m))
        .collect();
    markers
        .iter()
        .filter(|m| !defined.contains(&m.milestone))
        .map(|m| {
            format!(
                "{}:{}: work marker references {}, which has no `## {}` section in {ROADMAP}",
                m.path, m.line, m.milestone, m.milestone
            )
        })
        .collect()
}

/// Renders the open-work table that lives in ROADMAP.md.
pub(crate) fn render_table(markers: &[Marker]) -> String {
    if markers.is_empty() {
        return String::from("_No open work markers._\n");
    }
    let mut out = String::from("| Milestone | Where | What |\n| --- | --- | --- |\n");
    for m in markers {
        out.push_str(&format!(
            "| {} | `{}` | {} |\n",
            m.milestone,
            m.path,
            m.text.replace('|', "\\|")
        ));
    }
    out
}

/// The generated table currently in `roadmap`, if the block exists.
pub(crate) fn current_table(roadmap: &str) -> Option<String> {
    let (_, inner, _) = split_block(roadmap)?;
    Some(inner.strip_prefix('\n').unwrap_or(inner).to_owned())
}

/// `roadmap` with the generated block's contents replaced by `table`.
pub(crate) fn replace_table(roadmap: &str, table: &str) -> Option<String> {
    let (before, _, after) = split_block(roadmap)?;
    Some(format!("{before}{TABLE_BEGIN}\n{table}{TABLE_END}{after}"))
}

fn split_block(roadmap: &str) -> Option<(&str, &str, &str)> {
    let begin = roadmap.find(TABLE_BEGIN)?;
    let inner_start = begin + TABLE_BEGIN.len();
    let end = inner_start + roadmap[inner_start..].find(TABLE_END)?;
    Some((
        &roadmap[..begin],
        &roadmap[inner_start..end],
        &roadmap[end + TABLE_END.len()..],
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn m(number: u32, part: Option<char>) -> Milestone {
        Milestone { number, part }
    }

    fn scan(text: &str) -> Scan {
        let mut scan = Scan::default();
        scan_text("f.rs", text, &mut scan);
        scan
    }

    #[test]
    fn well_formed_marker_is_collected() {
        let s = scan(&format!("fn x() {{}}\n// {TAG}(M3): wire up the socket\n"));
        assert!(s.violations.is_empty(), "{:?}", s.violations);
        assert_eq!(
            s.markers,
            vec![Marker {
                milestone: m(3, None),
                path: "f.rs".into(),
                line: 2,
                text: "wire up the socket".into(),
            }]
        );
    }

    #[test]
    fn split_milestones_have_a_letter() {
        let s = scan(&format!("// {TAG}(M9b): later\n// {TAG}(M10): after\n"));
        assert!(s.violations.is_empty(), "{:?}", s.violations);
        assert_eq!(s.markers[0].milestone, m(9, Some('b')));
        assert_eq!(s.markers[0].milestone.to_string(), "M9b");
        assert_eq!(s.markers[1].milestone.to_string(), "M10");
        assert!(m(9, None) < m(9, Some('b')) && m(9, Some('b')) < m(10, None));
    }

    #[test]
    fn block_comment_terminator_is_stripped() {
        let s = scan(&format!("/* {TAG}(M12): later */"));
        assert_eq!(s.markers[0].milestone, m(12, None));
        assert_eq!(s.markers[0].text, "later");
    }

    #[test]
    fn malformed_markers_are_violations() {
        for bad in [
            format!("// {TAG}: no milestone"),
            format!("// {TAG}(m1): lowercase"),
            format!("// {TAG}(M): no number"),
            format!("// {TAG}(M1) missing colon"),
            format!("// {TAG}(1): no M"),
            format!("// {TAG}(M9B): capital part"),
            format!("// {TAG}(M9bc): two letters"),
        ] {
            let s = scan(&bad);
            assert!(s.markers.is_empty(), "accepted: {bad}");
            assert_eq!(s.violations.len(), 1, "for: {bad}");
        }
    }

    #[test]
    fn empty_description_is_a_violation() {
        let s = scan(&format!("// {TAG}(M1):   "));
        assert!(s.markers.is_empty());
        assert!(s.violations[0].message.contains("no description"));
    }

    #[test]
    fn longer_identifiers_are_not_markers() {
        let s = scan(&format!(
            "let {TAG}S = 1; let MY_{TAG} = 2; let x{TAG} = 3;"
        ));
        assert!(s.markers.is_empty());
        assert!(s.violations.is_empty());
    }

    #[test]
    fn banned_tag_is_a_violation() {
        let s = scan(&format!("// {BANNED} later"));
        assert_eq!(s.violations.len(), 1);
        assert!(s.violations[0].to_string().starts_with("f.rs:1: "));
    }

    #[test]
    fn markdown_lock_and_license_files_are_not_scanned() {
        assert!(!is_scanned(Path::new("ROADMAP.md")));
        assert!(!is_scanned(Path::new("Cargo.lock")));
        assert!(!is_scanned(Path::new("LICENSE")));
        assert!(is_scanned(Path::new("crates/a/src/lib.rs")));
        assert!(is_scanned(Path::new(".github/workflows/ci.yml")));
    }

    #[test]
    fn table_rendering_escapes_pipes() {
        let markers = vec![Marker {
            milestone: m(1, None),
            path: "a.rs".into(),
            line: 9,
            text: "a | b".into(),
        }];
        assert_eq!(
            render_table(&markers),
            "| Milestone | Where | What |\n| --- | --- | --- |\n| M1 | `a.rs` | a \\| b |\n"
        );
        assert_eq!(render_table(&[]), "_No open work markers._\n");
    }

    #[test]
    fn table_block_round_trips() {
        let doc = format!("# Roadmap\n\n{TABLE_BEGIN}\nold\n{TABLE_END}\n\nafter\n");
        assert_eq!(current_table(&doc).as_deref(), Some("old\n"));
        let updated = replace_table(&doc, "new\n").expect("block present");
        assert_eq!(
            updated,
            format!("# Roadmap\n\n{TABLE_BEGIN}\nnew\n{TABLE_END}\n\nafter\n")
        );
        assert_eq!(current_table(&updated).as_deref(), Some("new\n"));
        assert!(current_table("no block here").is_none());
    }

    #[test]
    fn markers_must_reference_defined_milestones() {
        let roadmap = "## M0 — Plan\n## M1 — Renderer\n## M9b — Gaps\n### M7 is not a section\n";
        let marker = |milestone, path: &str| Marker {
            milestone,
            path: path.into(),
            line: 1,
            text: "x".into(),
        };
        let markers = vec![
            marker(m(1, None), "a.rs"),
            marker(m(7, None), "b.rs"),
            marker(m(9, Some('b')), "c.rs"),
            marker(m(9, None), "d.rs"),
        ];
        let problems = check_milestones_exist(&markers, roadmap);
        assert_eq!(problems.len(), 2, "{problems:?}");
        assert!(problems[0].starts_with("b.rs:1: "));
        assert!(problems[1].contains("references M9, which has no `## M9` section"));
    }
}
